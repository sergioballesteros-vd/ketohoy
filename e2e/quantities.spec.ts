    const product = { id: 'kh005-catalog', mercadonaId: 'kh005-catalog', name: 'Pollo de catálogo', category: 'meat', ketoScore:5, unitPrice: 5, imageUrl: null, brand: 'Mercadona', classification: { score: 5, label: 'Estimación por categoría', source: 'category_estimate', evidence: 'category_name' } }
    let items: Array<{ id: string; checked: boolean; sourceType: string; quantity: string | null; requiredQuantity: number | null; originalIngredientText: string | null; purchaseQuantity: number | null; product: typeof product }> = [{ id: 'need', checked: false, sourceType: 'recipe', quantity: null, requiredQuantity: 300, originalIngredientText: '300 g', purchaseQuantity: null, product }, { id: 'legacy', checked: false, sourceType: 'legacy', quantity: '1', requiredQuantity: null, originalIngredientText: null, purchaseQuantity: null, product }]
